const dictionaries: Record<Language, Dictionary> = { vi: { ...vi, ...megaVi }, en: { ...en, ...megaEn } };

const LanguageContext = createContext<LanguageContextValue | null>(null);

function interpolate(value: string, params?: TranslateParams) {
  if (!params) return value;

  return Object.entries(params).reduce((currentValue, [key, paramValue]) => {
    return currentValue.replaceAll(`{${key}}`, String(paramValue));
  }, value);
}

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  // Use a stable default for the initial render to match the server output.
  const [language, setLanguageState] = useState<Language>("vi");

  // On mount, read the persisted language from localStorage and apply it.
  useEffect(() => {
    let timer: number | undefined;
    try {
      const saved = typeof window !== "undefined" ? window.localStorage.getItem("homex-pos-language") : null;
      if (saved === "vi" || saved === "en") {
        timer = window.setTimeout(() => {
          setLanguageState((prev) => (prev === saved ? prev : (saved as Language)));
        }, 0);
      }
    } catch {
      /* ignore localStorage errors */
    }

    return () => {
      if (timer) clearTimeout(timer);
    };
  }, []);

  // Keep the document language and persisted value in sync when language changes.
  useEffect(() => {
    document.documentElement.lang = language;
    try {
      window.localStorage.setItem("homex-pos-language", language);
    } catch {
      /* ignore localStorage errors */
    }
  }, [language]);

  const setLanguage = useCallback((nextLanguage: Language) => {
    setLanguageState(nextLanguage);
  }, []);

  const toggleLanguage = useCallback(() => {
    setLanguageState((prev) => (prev === "vi" ? "en" : "vi"));
  }, []);

  const value = useMemo<LanguageContextValue>(() => {
    return {
      language,
      setLanguage,
      toggleLanguage,
      t: (key: string, params?: TranslateParams) => interpolate(dictionaries[language][key] || key, params),
    };
  }, [language, setLanguage, toggleLanguage]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);

  if (!context) {
    throw new Error("useLanguage must be used inside LanguageProvider");
  }

  return context;
}










